import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.resolve(__dirname, "../..")
const legalSourcePath = path.join(repoRoot, "webapp/messages/en/content/legal.md")
const outputPath = path.join(repoRoot, "webapp/lib/generated-legal-content.ts")

function flushParagraph(buffer, blocks) {
  if (buffer.length === 0) return
  blocks.push({
    type: "paragraph",
    text: buffer.join("\n").trim(),
  })
  buffer.length = 0
}

async function main() {
  const source = await fs.readFile(legalSourcePath, "utf8")
  const lines = source.replace(/\r\n/g, "\n").split("\n")

  /** @type {{ title: string; blocks: { type: "paragraph"; text: string }[] }[]} */
  const sections = []
  let currentSection = null
  const paragraphBuffer = []

  for (const rawLine of lines) {
    const line = rawLine.replace(/\s+$/, "")
    if (line.startsWith("# ")) continue

    if (line.startsWith("## ")) {
      if (currentSection) {
        flushParagraph(paragraphBuffer, currentSection.blocks)
      }
      currentSection = {
        title: line.slice(3).trim(),
        blocks: [],
      }
      sections.push(currentSection)
      continue
    }

    if (!currentSection) continue

    if (line.trim() === "") {
      flushParagraph(paragraphBuffer, currentSection.blocks)
      continue
    }

    paragraphBuffer.push(line.trim())
  }

  if (currentSection) {
    flushParagraph(paragraphBuffer, currentSection.blocks)
  }

  const output = `/* eslint-disable */
// This file is generated by webapp/scripts/generate-legal-content.mjs from webapp/messages/en/content/legal.md.
// Do not edit this file directly.

export type LegalBlock = {
  type: "paragraph"
  text: string
}

export type LegalSection = {
  title: string
  blocks: LegalBlock[]
}

export const LEGAL_CONTENT_SECTIONS = ${JSON.stringify(sections, null, 2)} as const satisfies readonly LegalSection[]
`

  await fs.writeFile(outputPath, output)
  process.stdout.write(`Generated legal content from ${path.relative(repoRoot, legalSourcePath)}\n`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
